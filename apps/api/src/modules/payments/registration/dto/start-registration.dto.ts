import { BD_DISTRICTS, EDUCATION_TYPES, isDemoEmail, normalizeBdMobile } from '@sirat/shared';
import { Transform } from 'class-transformer';
import {
  IsEmail,
  IsIn,
  IsOptional,
  IsString,
  IsUUID,
  Length,
  Matches,
  MaxLength,
  registerDecorator,
  type ValidationOptions,
} from 'class-validator';
import { normalizeEmail } from '../../../auth/dto/login.dto';
import { IsAcceptablePassword } from '../../../auth/password-policy';

export const trim = ({ value }: { value: unknown }): unknown =>
  typeof value === 'string' ? value.trim().replace(/\s+/g, ' ') : value;

/**
 * Refuses the demo data's marker domain (DEMO_EMAIL_DOMAIN), so no real registration can look like a demo row and be
 * cleared with them. Only that exact domain: CI fixtures use other .invalid domains. Worded like any invalid address.
 */
function IsNotDemoEmail(options?: ValidationOptions) {
  return (object: object, propertyName: string) =>
    registerDecorator({
      name: 'isNotDemoEmail',
      target: object.constructor,
      propertyName,
      options: { message: 'Enter a valid email address', ...options },
      validator: { validate: (value: unknown) => typeof value !== 'string' || !isDemoEmail(value) },
    });
}

/** 01XXXXXXXXX, or the raw input when it is not a Bangladeshi mobile number (the pattern then refuses it). */
export const toBdMobile = ({ value }: { value: unknown }): unknown =>
  typeof value === 'string' ? (normalizeBdMobile(value) ?? value) : value;

/**
 * The registration form (owner-approved fields, plan Q2). Never a role, an amount or a fee: unknown fields are
 * refused by the global ValidationPipe (whitelist + forbidNonWhitelisted).
 */
export class StartRegistrationDto {
  /** Generated by the browser once per form submit: a double click returns the same payment. */
  @IsUUID()
  startRequestId!: string;

  @Transform(trim)
  @IsString()
  @Length(2, 100)
  name!: string;

  @Transform(toBdMobile)
  @IsString()
  @Matches(/^01[3-9][0-9]{8}$/, { message: 'Enter a Bangladeshi mobile number, e.g. 01712345678' })
  phone!: string;

  @Transform(normalizeEmail)
  @IsEmail({}, { message: 'Enter a valid email address' })
  @IsNotDemoEmail()
  @MaxLength(254)
  email!: string;

  @IsString()
  @IsAcceptablePassword()
  password!: string;

  @IsIn(BD_DISTRICTS)
  district!: string;

  @Transform(trim)
  @IsString()
  @Length(2, 150)
  institution!: string;

  @IsIn(EDUCATION_TYPES)
  educationType!: string;

  @IsUUID()
  gradeLevelId!: string;

  @IsOptional()
  @Transform(trim)
  @IsString()
  @Matches(/^[A-Za-z0-9_-]{3,40}$/, { message: 'Promo codes use letters, digits, "-" or "_"' })
  promoCode?: string;
}

/** POST /registrations/quote: the promo field alone, with the start's rule. */
export class QuoteRegistrationDto {
  @IsOptional()
  @Transform(trim)
  @IsString()
  @Matches(/^[A-Za-z0-9_-]{3,40}$/, { message: 'Promo codes use letters, digits, "-" or "_"' })
  promoCode?: string;
}
